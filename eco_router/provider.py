import json
import math
import re
import httpx


class UpstreamError(Exception):
    def __init__(self, message, status=502):
        self.message, self.status = message, status
        super().__init__(message)


def estimate_tokens(value):
    text = value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)
    return max(1, math.ceil(len(text.encode('utf-8')) / 4))


class Provider:
    def __init__(self, settings, client):
        self.settings, self.client = settings, client

    async def complete(self, messages, model, tier, options, prompt='', error_context=None):
        if error_context:
            messages = [*messages, {'role': 'user', 'content':
                f'Previous output failed validation: {error_context}\nReturn a corrected complete answer.'}]
        payload = {'model': model, 'messages': messages, **options, 'stream': False}
        if self.settings.mock:
            content = self.mock_answer(prompt, tier, options, error_context)
            message = {'role': 'assistant', 'content': content}
            usage = {'prompt_tokens': estimate_tokens(messages), 'completion_tokens': estimate_tokens(content)}
            return message, usage, 'stop', True
        try:
            response = await self.client.post(
                self.settings.endpoint + '/chat/completions', json=payload,
                headers={'Authorization': f'Bearer {self.settings.api_key}'})
            response.raise_for_status()
            data = response.json()
            choice = data['choices'][0]
            message = choice['message']
            if not isinstance(message, dict) or (not isinstance(message.get('content'), str) and not message.get('tool_calls')):
                raise ValueError('Invalid assistant message')
            raw_usage = data.get('usage') or {}
            if not isinstance(raw_usage, dict):
                raw_usage = {}
            estimated = not all(isinstance(raw_usage.get(k), int) and raw_usage[k] >= 0
                                for k in ('prompt_tokens', 'completion_tokens'))
            usage = ({'prompt_tokens': estimate_tokens(messages), 'completion_tokens': estimate_tokens(message)}
                     if estimated else {k: raw_usage[k] for k in ('prompt_tokens', 'completion_tokens')})
            return message, usage, choice.get('finish_reason') or 'stop', estimated
        except httpx.TimeoutException as exc:
            raise UpstreamError('DigitalOcean inference timed out.', 504) from exc
        except httpx.HTTPStatusError as exc:
            status = exc.response.status_code
            message = ('DigitalOcean rate limit reached.' if status == 429 else
                       f'DigitalOcean returned HTTP {status}; check credentials, model IDs, and endpoint.')
            raise UpstreamError(message, 429 if status == 429 else 502) from exc
        except (httpx.RequestError, ValueError, KeyError, IndexError, TypeError) as exc:
            raise UpstreamError('Invalid or unreachable DigitalOcean inference response.') from exc

    def mock_answer(self, prompt, tier, options, error_context):
        if self.settings.demo_fail_eco and tier == 'eco' and not error_context:
            return ''
        fmt = options.get('response_format', {}).get('type')
        if fmt in {'json_object', 'json_schema'} or re.search(r'\bjson\b', prompt, re.I):
            # Arbitrary JSON schemas are deliberately not fabricated in demo mode.
            errors = [line.strip() for line in prompt.splitlines() if re.search(r'\b(ERROR|WARN)\b', line)]
            return json.dumps({'mock': True, 'tier': tier, 'items': errors or [prompt.split(':')[-1].strip()]})
        if re.search(r'\bpython\b', prompt, re.I):
            return '```python\n# Mock scaffold; replace with real model output.\ndef solve(data):\n    return data\n```'
        if tier == 'heavy':
            return ('[MOCK · Heavy] Suggested analysis: separate ingestion from processing with a bounded queue; '
                    'use idempotent consumers, retries with backoff, and observability. For algorithm refactoring, '
                    'profile the bottleneck, replace repeated scans with indexed lookups, and preserve invariants. '
                    'This is a deterministic demonstration, not an analysis generated by a model.')
        if tier == 'balanced':
            return '[MOCK · Balanced] Implementation outline: validate inputs, isolate transformations, and cover edge cases.'
        if re.search(r'bullet|format|list', prompt, re.I):
            values = prompt.split(':', 1)[-1]
            return '\n'.join('- ' + x.strip() for x in values.split(',') if x.strip())
        return '[MOCK · Eco] ' + prompt[:500]
